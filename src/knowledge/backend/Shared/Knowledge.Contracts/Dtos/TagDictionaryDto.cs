namespace Knowledge.Contracts.Dtos;

// FR-06, FR-09, SC-05, SC-09, #634: タグ辞書の契約（IADR-0152）。
//
// SC-09 が 2026-08-02 に確定した規則（参照が 1 件でもあるタグは削除拒否・改名は既存文書へ追随・
// 削除前に使用件数を示す）は**すべて契約側の機能**である。**辞書が無いと 1 つも満たせない。**
//
// **使用件数つきの 1 件。**
//
// `UsageCount` は**現行版の文書の件数**である（IADR-0152 決定 2）——
// **版履歴は数えない**。版履歴は append-only で付け替えられないため、数えると
// **一度でも使われたタグを永久に削除できず**、SC-09 の「使用件数 0 件のときに限り削除できる」が空文になる。
// **アーカイブ済みの文書は数える**。アーカイブ済みでもタグは付け替えられる（実測）ので、
// 数えても管理者は行動できる。除くと、削除した直後にアーカイブ済み文書が消えたタグを指したままになる。
//
// **Qdrant の facet 件数とは別物である**——あちらは到達可能チャンクの件数で、主体ごとに変わる。
public record TagDto(Guid Id, string Name, int UsageCount);

// FR-09, SC-09, #634: 辞書へタグを追加する。
// **識別子は辞書が採番する**（呼び出し側から与えない。改名で変わらない値を外から決めさせない）。
public record CreateTagRequest(string Name);

// FR-09, SC-09, #635: 辞書のタグを改名する（SC-09「改名は許して既存の文書が新しい名前へ追随する」）。
//
// **識別子は変えない。** 変わるのは表示名だけであり、文書は識別子を参照しているので追随は自動である
// （[[IADR-0153]] 決定 1・3）。**版は増えない**——改名は文書の内容変更ではない（同 決定 3）。
public record RenameTagRequest(string Name);

// FR-09, SC-09, #635: 改名の結果。
//
// `RepublishedDocuments` は**射影を作り直すために `DocumentUpdated` を再発行した文書の数**である。
// **`Tag.UsageCount` と同じ値になる**——どちらも「現行版でこのタグを持つ文書の数」であり、
// 2 通りの数え方を持たない。**添えるのは、改名が下流へ何件波及したかを管理者が確認できるようにするため**で、
// Qdrant / Wiki.js の反映は非同期なので「0 件だった」と「まだ届いていない」を切り分けられる。
public record RenameTagResponse(TagDto Tag, int RepublishedDocuments);

// FR-09, SC-05, SC-09, #634: 辞書の値集合（管理者スコープ）。
//
// **一般利用者の応答（`AttributeValuesResponse.Values`）とは別物である。**
// 一般利用者へ返すのは「到達できる文書に実際に付与されている値」だけで、**辞書そのものではない**
// （ADR-0043 決定 1 が辞書を丸ごと返すことを明示的に禁じている。IADR-0152 決定 4）。
// **辞書は管理面、facet は利用者面**という 2 経路を意図的に保つ。
public record TagDictionaryResponse(List<TagDto> Tags);
