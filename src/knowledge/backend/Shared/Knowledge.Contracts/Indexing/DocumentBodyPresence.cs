namespace Knowledge.Contracts.Indexing;

// FR-02, FR-03, SC-02, ADR-0070 決定 4, #1193, [[IADR-0358]] 決定 1・3:
// **本文を持たない文書を「メタデータ点」1 つで索引へ載せるための、取り込み側と検索側の共通契約。**
//
// ADR-0070 決定 4 は「本文由来のチャンク・埋め込みは作らない（作れない）。タイトル・パス・データソース・
// 更新日時などのメタデータで FR-03 の検索に載せる」と定める。索引の単位はチャンクなので、
// 本文が無い文書は**点が 1 つも作られず、検索結果に現れる経路そのものが無かった**（#1193 の実測）。
//
// そこで**題名から作った索引テキストを持つ点を 1 つだけ置き、その点に本フラグを載せる**。
//
// 🔴 **`text` ペイロードは「本文」ではなく「索引テキスト」である**（[[IADR-0358]] 決定 2 の代償）。
// メタデータ点では題名由来の文字列が入る。**復元側は必ず `Excerpt` を通すこと** ——
// 通さないと、メタデータが本文の抜粋として画面（SC-02）と LLM（FR-04 の出典）へ出る。
//
// **キーだけでなく射影（関数）をここへ置く理由**: ペイロードキーの文字列は両サービスへ複写して
// 揃えてきたが（[[IADR-0014]]）、**関数を複写すると必ず割れる**（片方だけ直すと静かに漏れる）ため、
// `CjkBigramPayload` と同じく共有契約へ 1 つだけ置く（[[IADR-0339]] 決定 1 と同じ理由）。
public static class DocumentBodyPresence
{
    /// <summary>
    /// 点が本文由来かどうかを表す真偽ペイロードのキー。取り込み側の書き込みと検索側の復元が
    /// 同じ 1 つの値を使う。
    /// </summary>
    public const string PayloadKey = "has_body";

    /// <summary>
    /// **キーを持たない点は「本文あり」である。** 本項目より前に索引された点はすべて本文チャンクであり、
    /// 欠落は「本文あり」を正しく表す（[[IADR-0358]] 決定 3。backfill は要らない）。
    /// 逆に倒すと、再索引が済むまで全文書が「本文なし」と表示される。
    /// </summary>
    public const bool DefaultWhenAbsent = true;

    /// <summary>
    /// 索引テキストから、利用者へ返す本文抜粋（<c>SearchResultDto.Text</c>）を導く。
    /// **本文なしの点では空文字列**である —— 索引に載せたメタデータをサービスの外へ本文として出さない。
    /// </summary>
    public static string Excerpt(string? indexedText, bool hasBody) =>
        hasBody ? indexedText ?? string.Empty : string.Empty;
}
