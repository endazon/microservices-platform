namespace Knowledge.IntegrationTests.Messaging;

// ADR-0027, IADR-0302, IADR-0305, #1038 / #1059:
// **fan-out の統合テスト 2 クラスを同時に走らせない**ためのコレクション定義。
//
// ■ なぜ要るのか（実測に基づく）
//   Integration の run ログ 5 本から 2 件の実行窓を復元したところ、**分布が二峰**だった。
//
//     緑の run（3 本）: 341ms / 2s / 3s / 646ms / 1s / 2s
//     赤の run（2 本）: **予算 30 秒を使い切る**（35s / 33s / 30s / 30s）
//
//   🔴 **中間（10 秒・20 秒）が 1 件も無い。** 「負荷でじわじわ遅くなる」形ではないので、
//   **予算を 60 秒へ伸ばしても救われない**（#1038 が禁じた直し方は実測でも無効である）。
//
//   そして**赤の 2 本では 2 クラスの実行窓が重なり、緑の 3 本では 20〜51 秒離れていた**。
//   各クラスは Testcontainers 2 つ（Postgres / RabbitMQ）と Wolverine ホスト 3 つを起こすため、
//   2 クラスが重なる窓は 2 コアのランナー上で**最も重い局面**である。
//
// ■ 🔴 この相関には交絡がある。「重なりが原因である」とは書いていない
//   落ちるテストは 30 秒居座るので、**落ちれば重なりやすい**（逆向きの因果）。
//   本定義が主張するのは次の 2 点だけである。
//     - 重なりは**取り除ける**。副作用は実行時間だけで、**検査の強さは 1 ミリも落ちない**
//       —— fan-out が本当に壊れていれば、直列化しても同じように落ちる
//     - 取り除いた後も落ちるなら、**「同時実行による混雑」を証拠つきで除外できる**
//   **どちらへ転んでも #1038 は前へ進む。** それが本定義の目的である。
//
// ■ DisableParallelization を立てる理由
//   混雑の候補を消すのが目的なので、**当該コレクションの実行中は他のコレクションと重ねない**。
//   コストは実行時間だけである（当該 2 クラスの実測は緑なら合計 3 秒未満、
//   セットアップ〜破棄を含めても 20 秒前後。Integration ジョブは 7〜9 分 / timeout 30 分）。
//
// 🔴 **`IClassFixture` はコレクションに関係なくクラス単位のままである。**
//   Postgres / RabbitMQ のコンテナは**今までどおりクラスごとに別々**であり、
//   本定義でブローカを共有させてはいない（共有させるとクラス跨ぎの競合コンシューマを
//   自分で作り込むことになる —— それはこのテストが検出したい退行そのものである）。
// 🔴 ［2026-08-30 追記 / #1073］**上の相関は交絡であり、直列化では直らなかった。**
//   本定義が着地した後の run 33309205241（`beaeb9e4`）で同じ 2 件が同じ形で落ちた。
//   これにより本定義の主目的（「同時実行による混雑」を証拠つきで除外する）は**達せられた** ——
//   混雑は原因ではない。真因は **Wolverine の `ApplicationAssembly` がプロセス全体で
//   共有され、後発のホストが相手のハンドラを拾う**ことであり、
//   共通ヘルパ（`AddPlatformWolverineStep`）で探索アセンブリを明示固定して閉じた
//   （実測と判断は `.ai-context/adr/IADR-0326_wolverine-application-assembly-pinning.md`）。
//
//   🔴 **それでも本定義は残す。** 残す理由は「効いているから」ではない ——
//   取り除いても実行時間が数十秒戻るだけであり、**取り除くことを支える新しい実測を
//   持っていない**からである（測らずに戻すのは、測らずに入れるのと同じ損なわれ方である）。
//   **上の「重なりが原因である」とは書いていないという断りは、結果的に正しかった。**
[CollectionDefinition(Name, DisableParallelization = true)]
public sealed class FanOutTestCollection
{
    public const string Name = "fan-out messaging (直列)";
}
