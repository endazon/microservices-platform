// SC-20 主要素 3, FR-20, ADR-0037 決定 3・4: 同期対象フォルダの入力を整える純関数。
//
// **純関数だけを置く。** 描画も問い合わせもしない（`deviceState.ts` と同じ作法）。
//
// 🔴 **ここは検証ではない。** 値域の防壁はサーバ側にある（空でない・前後の `/` の除去・重複不可・
// 最大 100 件・各 1024 文字以内。違反は 400）。ここが担うのは
//   ① 送る前に**利用者へ見せる形**（前後の空白と `/` を落とした表示）
//   ② **押せないボタンを押させない**（空・重複のときは追加ボタンを無効にする）
// の 2 つだけである。**同じ規則を画面側で実装し直すと、2 つの規則が静かにずれる。**

/**
 * 入力欄の文字列を、送信する形（＝サーバが正規化した後と同じ形）へ整える。
 *
 * 前後の空白を落とし、先頭・末尾の `/` を除く（`/仕事/メモ/` → `仕事/メモ`）。
 * **途中の `/` は触らない**（階層の区切りであり、潰すとフォルダが別物になる）。
 */
export function normalizeFolderPath(raw: string): string {
  return raw.trim().replace(/^\/+/, '').replace(/\/+$/, '');
}

/**
 * いま追加できるか（空でない・既にある同じパスではない）。
 *
 * **比較は正規化した後で行う。** `仕事/メモ` と `/仕事/メモ/` は同じフォルダであり、
 * 生の文字列で比べると「追加できたのにサーバが 400 を返す」形になる。
 */
export function canAddFolder(raw: string, existing: readonly string[]): boolean {
  const path = normalizeFolderPath(raw);
  if (path === '') return false;
  return !existing.some((e) => normalizeFolderPath(e) === path);
}
