// FR-05, UC-04, SC-06, ADR-0036, ADR-0074: 所有者（ABAC 文書属性 `owner`）の語彙。
//
// **画面ではなく語彙の単位で置く**（`department.ts` と同じ理由）。`owner` は SC-06 の写像表だけでなく、
// SC-05 の管理者経路・FR-21 の本文書き込み判定（`doc.owner ∈ { ${current_user} }`）でも同じキーを指す。
//
// 計画の正は `06_technical/09_datasource-connectors.md` §システム投入経路（解決順
// ① Keycloak のユーザー検索 → ② データソース単位の写像表 → 予約値）と
// `07_abac-attribute-model.md` §文書の基本属性である。
//
// **値集合は持たない。** 値は基盤の利用者識別子（ログイン名）であり、その値域は IdP が持つ。
// **実装が候補を列挙しない** —— 列挙すると退職者や新入社員のたびに画面が古くなる。
//
// 🔴 **写像先の実在検証は後段が行う。** 画面だけで検証すると、API を直接叩いた経路で
// 偽の所有者が入り、ADR-0036 の裁量制御が意図しない相手に開く（ADR-0074 決定 4）。

// 🔴 **属性キー（`'owner'`）の定数はここに置かない。**
// `confidentiality` / `department` / `lifecycle` の 3 つと違い、`owner` は SC-06 のフォームが
// 組み立てる `defaultAttributes` のキーにならない（写像表は**別の器**であり、`ownerMappings` として
// 送る）。**使い道の無い定数を置くと Knip の未使用 export が増え、床が動く。**
// 属性キーそのものはバックエンド `DataSource.OwnerKey` / `DocumentBodyIntake.OwnerKey` が正である。

/**
 * 解決できなかったときに後段が入れる**予約値**（既定値ではない）。
 *
 * 計画は「`system` / `unassigned` は解決できなかったことの記録であり、恒久的に積み上がるなら
 * コネクタが更新者を運んでいないという報告である」と定める（バックエンド
 * `DataSource.UnresolvedOwner` と同じ値。IADR-0199）。
 *
 * 🔴 **ただし `owner` については件数を完了判定に使わない**（ADR-0074 決定 3）——
 * `filesystem` は構造上更新者を運べず、計画はこれを**意図的な縮退**と裁定した。
 * **写像表を入れても現在登録されているデータソースの予約値は減らない。**
 *
 * 画面では「写像できなければこの値になる」ことを利用者へ伝えるためだけに使う。**この値を送らない。**
 */
export const UNRESOLVED_OWNER = 'system';
